const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const root = new URL('../../../../../docs/galaxy/', import.meta.url).pathname;
const base = process.env.GALAXY_URL || 'http://127.0.0.1:1435';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE,args:['--enable-unsafe-webgpu']});
const suffix=process.env.GALAXY_SUFFIX || '';
const results=[];const errors=[];
const page=await browser.newPage({viewport:{width:720,height:600},reducedMotion:'reduce'});
page.on('pageerror',e=>errors.push(e.message));
for(const platform of ['windows','macos']) {
 await page.goto(`${base}/dev/graph-galaxy/?count=200&platform=${platform}&theme=light`);
 await page.waitForFunction(()=>document.querySelector('.graph-galaxy-canvas')?.dataset.nodes==='200');
 await page.getByRole('button',{name:'Graph settings'}).click();
 await page.screenshot({path:`${root}${platform}-narrow-settings${suffix}.png`});

 const search=page.getByPlaceholder('Filter by title…');
 await search.fill('perspective'); results.push(`${platform}: search input accepted`);
 await page.getByRole('button',{name:'Graph settings'}).click();
 await page.locator('.graph-canvas').focus();await page.keyboard.press('ArrowRight');
 await page.waitForSelector('[role=status]');
 const start=Date.now();await page.keyboard.press('Enter');await page.waitForFunction(()=>!!document.body.dataset.openedNote);
 assert.ok(Date.now()-start<400,'reduced-motion fly-to must skip animation');
 results.push(`${platform}: narrow settings, keyboard selection/open, reduced motion passed`);
}
await page.goto(`${base}/dev/graph-galaxy/?count=2000&platform=windows&renderer=2d`);
await page.getByText('3D unavailable — showing the 2D graph.').waitFor();
assert.equal(await page.locator('.graph-galaxy-canvas').count(),0);
await page.locator('.graph-canvas').focus();await page.keyboard.press('ArrowRight');await page.keyboard.press('Enter');
await page.waitForFunction(()=>!!document.body.dataset.openedNote);
await page.screenshot({path:root+'fallback-2d'+suffix+'.png'});
results.push('GPU contexts denied: capped 2D fallback and keyboard open passed');
const pointerPage = await browser.newPage({viewport:{width:1440,height:1000}});
pointerPage.on('pageerror', error => errors.push(error.message));
await pointerPage.goto(`${base}/dev/graph-galaxy/?count=200`);
await pointerPage.waitForFunction(() => document.querySelector('.graph-galaxy-host')?.dataset.layout === 'settled');
await pointerPage.mouse.move(700,500); await pointerPage.mouse.down();
await pointerPage.mouse.move(760,540); await pointerPage.mouse.move(700,500); await pointerPage.mouse.up();
await pointerPage.waitForTimeout(750);
assert.equal(await pointerPage.evaluate(() => document.body.dataset.openedNote),undefined);
results.push('Orbit returning to its starting point does not open a note');
await pointerPage.locator('.graph-canvas').focus(); await pointerPage.keyboard.press('ArrowRight');
await pointerPage.waitForSelector('[role=status]');
const point = await pointerPage.locator('[role=status]').evaluate(element => ({x:parseFloat(element.parentElement.style.left)-12,y:parseFloat(element.parentElement.style.top)-12}));
await pointerPage.mouse.move(1350,850);
await pointerPage.waitForFunction(() => document.querySelector('.graph-galaxy-canvas').dataset.highlightLinks === '0');
await pointerPage.mouse.move(point.x,point.y);
await pointerPage.waitForFunction(() => Number(document.querySelector('.graph-galaxy-canvas').dataset.highlightLinks) > 0);
await pointerPage.screenshot({path:root+'selected-star'+suffix+'.png'});
await pointerPage.mouse.click(point.x,point.y);
await pointerPage.waitForFunction(() => !!document.body.dataset.openedNote);
results.push('Pointer hover glow/links and fly-to/open passed');
await pointerPage.close();
const fallbackPage = await browser.newPage();
fallbackPage.on('pageerror', error => errors.push(error.message));
await fallbackPage.addInitScript(() => Object.defineProperty(navigator, 'gpu', {configurable:true,value:undefined}));
await fallbackPage.goto(`${base}/dev/graph-galaxy/?count=200`);
await fallbackPage.waitForFunction(() => document.querySelector('.graph-galaxy-canvas')?.dataset.nodes === '200');
assert.equal(await fallbackPage.locator('.graph-galaxy-canvas').getAttribute('data-backend'), 'WebGL2');
results.push('WebGPU absent: automatic WebGL2 passed');
await writeFile(root+'interactions'+suffix+'.json',JSON.stringify({results,errors},null,2));
console.log({results,errors});
await browser.close();
assert.deepEqual(errors,[]);
